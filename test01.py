#python的变量操作
#1. 什么是变量？
#在 Python 中，变量是存储数据值的容器。与其他编程语言不同，Python 不需要声明变量类型，解释器会根据赋值自动推断变量类型。变量可以存储各种数据类型，如整数、浮点数、字符串、列表、字典等。变量名可以由字母、数字和下划线组成，但不能以数字开头，并且区分大小写。
#变量作用：存储数据  其他编程语言（java、c++、c#）作用复用操作
#变量值：25/25.66.   274777777777787     变量数据类型
#整数 /字符串 /浮点数
